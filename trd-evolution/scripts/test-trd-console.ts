/**
 * Test script for TRD EVOLUTION Console Briefing Recognition & Instant Executive Response
 */

import { IntentAgent } from '../src/api/integrations/chatbot/anthropic/agents/intent.agent';
import { CoordinatorAgent } from '../src/api/integrations/chatbot/anthropic/agents/coordinator.agent';
import { AgentContext } from '../src/api/integrations/chatbot/anthropic/agents/agent-types';

class MockPrismaRepository {
  agentMemoryEntry = {
    upsert: async () => {},
    findMany: async () => [],
    deleteMany: async () => {},
  };
  ragChunk = null;
  ragDocument = null;
}

function buildContext(overrides: Partial<AgentContext> = {}): AgentContext {
  return {
    instance: { name: 'trd-instance' },
    remoteJid: '5561999999999@s.whatsapp.com',
    bot: { id: 'trd-bot-main' },
    session: {},
    settings: {},
    content: '',
    pushName: 'Dr. Roberto Mendes',
    conversationHistory: [],
    ...overrides,
  };
}

async function runTests() {
  console.log('╔══════════════════════════════════════════════════════════╗');
  console.log('║   TRD EVOLUTION — Console Briefing & Executive Reply     ║');
  console.log('╚══════════════════════════════════════════════════════════╝\n');

  let passed = 0;
  let failed = 0;

  function assert(cond: boolean, msg: string) {
    if (cond) {
      console.log(`  ✅ ${msg}`);
      passed++;
    } else {
      console.log(`  ❌ ${msg}`);
      failed++;
    }
  }

  // Sample real briefing generated by site/index.html console
  const realBriefing = [
    '*TRD CONSULTORIA - ESPECIFICAÇÃO DE ENGENHARIA*',
    '----------------------------------------',
    '*Modalidade:* Starter MVP (Até 4 Telas / Fluxos Chave)',
    '*Escopo:* Sistema Web / Painel Operacional',
    '*Infraestrutura:* Docker Isolado, PostgreSQL, Nginx e Backups Automatizados',
    '*Governança:* Código-fonte 100% de Propriedade do Cliente + Contrato Gov.br',
    '*Prazo / SLA:* Resposta em até 4h úteis · Reunião em até 24h úteis',
    '*Condição:* 50% Entrada (Gov.br) + 50% Homologação Staging (R$ 9.800)',
    '*Solicitante:* Dr. Roberto Mendes (Clínica Santa Maria)',
    '----------------------------------------',
    '*Referência:* TRD-ENG-2026-8942',
    '----------------------------------------',
    'Olá Thiago, configurei este escopo no site da TRD e gostaria de um alinhamento técnico.'
  ].join('\n');

  // Test 1: IntentAgent Heuristic Classification
  console.log('━━━ 1. IntentAgent Recognition ━━━');
  const intentAgent = new IntentAgent();
  const intentClassified = await intentAgent.classify(realBriefing);
  assert(intentClassified === 'trd_console_lead', `Should classify as 'trd_console_lead' (got: ${intentClassified})`);

  // Test 2: Heuristic on message with TRD-ENG- code
  const shortMsg = 'Olá, gostaria de saber sobre a referência TRD-ENG-2026-1234';
  const intentShort = await intentAgent.classify(shortMsg);
  assert(intentShort === 'trd_console_lead', `Should classify TRD-ENG code as 'trd_console_lead' (got: ${intentShort})`);

  // Test 3: CoordinatorAgent Instant Qualification & Routing
  console.log('\n━━━ 2. CoordinatorAgent Executive Qualification Response ━━━');
  const mockRepo = new MockPrismaRepository();
  const coordinator = new CoordinatorAgent(undefined, mockRepo as any);

  const context = buildContext({
    content: realBriefing,
    pushName: 'Dr. Roberto Mendes',
  });

  const startTime = Date.now();
  const result = await coordinator.route(context);
  const latency = Date.now() - startTime;

  console.log(`  Execution Latency: ${latency}ms`);
  assert(latency < 100, `Execution should be instant under 100ms (got: ${latency}ms)`);
  assert(result.agentUsed === 'text', `Agent used should be text (got: ${result.agentUsed})`);
  assert(result.intent === 'trd_console_lead', `Intent should be trd_console_lead (got: ${result.intent})`);
  assert(result.finalResponse.includes('TRD-ENG-2026-8942'), 'Response should cite the engineering reference TRD-ENG-2026-8942');
  assert(result.finalResponse.includes('Roberto Mendes'), 'Response should greet the client (Roberto Mendes)');
  assert(result.finalResponse.includes('Starter MVP'), 'Response should reference Starter MVP');
  assert(result.finalResponse.includes('Gov.br'), 'Response should mention Gov.br digital contract');
  assert(result.finalResponse.includes('30 dias de sustentação'), 'Response should highlight 30 days warranty');
  assert(result.finalResponse.includes('Google Meet'), 'Response should propose 20-min Google Meet');
  assert(result.finalResponse.includes('Segunda a Sexta, das 8h às 18h'), 'Response should enforce business hours');
  assert(result.conversationHistory.length === 2, `Conversation history should be updated (got: ${result.conversationHistory.length})`);

  console.log('\n━━━ Preview of Generated Response ━━━');
  console.log(result.finalResponse);
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

  console.log(`Results: ${passed} passed, ${failed} failed.`);
  if (failed > 0) process.exit(1);
}

runTests().catch((err) => {
  console.error(err);
  process.exit(1);
});
